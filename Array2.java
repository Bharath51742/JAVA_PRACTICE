class Array2 {
    public static void main(String[] args) {
        int[] arr = new int[5];   
        arr[0] = 12;
        arr[1] = 15;
        arr[2] = 4;
        arr[3] = 34;
        arr[4] = 3;

        
        for (int j = 0; j < arr.length; j++) {
            System.out.println(arr[j]);
        }
    }
}
